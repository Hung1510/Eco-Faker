/**
 * SQLAlchemy is Python, and eco-faker has no Python bindings (it's an npm
 * package only) -- so unlike the two TypeScript targets above, this seed
 * script can't call `generate()` in-process. It shells out to the real
 * CLI to produce eco-data.json (via the same scripts/eco-seed.mjs this
 * scaffold already writes), then reads that JSON from Python. Same
 * "connection setup varies too much to infer" reasoning as Drizzle above
 * applies here too -- the SQLAlchemy Session/engine is left as a fill-in.
 */
export function buildSqlAlchemySeedScript(mapping: SchemaMapping, seed: number): OrmScaffoldResult {
  const tables = mappedTables(mapping);

  const insertBlocks = tables
    .map(({ table, targetModel, columns }) => {
      const camelTable = tableToCamel(table);
      const fieldLines = columns.map(({ canonical, target }) => `            ${target}=row["${columnToCamel(canonical)}"],`).join("\n");
      return `    rows = dataset["${camelTable}"]
    session.add_all([
        ${targetModel}(
${fieldLines}
        )
        for row in rows
    ])
    print(f"Inserted {len(rows)} ${camelTable} into ${targetModel}")`;
    })
    .join("\n\n");

  const contents = `# Generated by \`my-eco-gen init sqlalchemy\`. Fill in the TODO below, then:
# Run: python seed.py
#
# eco-faker has no Python bindings -- this shells out to the real CLI
# (via node, same as scripts/eco-seed.mjs) to produce eco-data.json, then
# reads that JSON here. Uses the column mapping in ./mapping.json -- review
# that file before trusting it, especially any column with confidence 0.
import json
import subprocess
from pathlib import Path

# TODO: replace with your project's real SQLAlchemy engine/session setup. Example:
#   from sqlalchemy import create_engine
#   from sqlalchemy.orm import Session
#   engine = create_engine("postgresql://user:pass@localhost/db")
#   session = Session(engine)
from models import ${[...new Set(tables.map((t) => t.targetModel))].join(", ")}  # TODO: point this at your real models module

def main():
    subprocess.run(["node", "scripts/eco-seed.mjs"], check=True)
    dataset = json.loads(Path("eco-data.json").read_text())

${insertBlocks}

    session.commit()

if __name__ == "__main__":
    main()
`;

  return {
    files: [
      { path: "scripts/eco-seed.mjs", contents: buildEcoSeedScript(seed) },
      { path: "seed.py", contents },
    ],
    nextSteps: [
      "Next steps:",
      "  1. npm install eco-faker   (if not already installed -- scripts/eco-seed.mjs needs it)",
      "  2. Edit seed.py: fill in your real SQLAlchemy engine/session and models import (marked TODO)",
      "  3. python seed.py   -- runs scripts/eco-seed.mjs for you, then inserts the result",
      "",
      "This one's a template, not a drop-in script -- eco-faker has no Python bindings, and your database connection setup can't be inferred from the schema alone.",
      "Review mapping.json before trusting it -- any column with confidence 0 had no confident match in your schema.",
    ],
    skippedTables: skippedTables(mapping),
  };
}
